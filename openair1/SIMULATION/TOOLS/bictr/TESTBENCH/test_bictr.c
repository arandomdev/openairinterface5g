void test_bictr_get_heights(bictr_desc_t *desc)
{
  double lons[] = {-111.633156, -111.627816, -111.636840};
  double lats[] = {35.590627, 35.590990, 35.589674};
  double tv[] = {1849.3716590974013, 1846.9569694686468, 1847.2267124525536};

  int err;
  char vf_heights[GMT_VF_LEN];
  if ((err = GMT_Open_VirtualFile(desc->gmt_sess, GMT_IS_DATASET, GMT_IS_PLP, GMT_OUT, NULL, vf_heights))) {
    printf("Fail: Unable to open VF\n");
    return;
  }

  if ((err = _bictr_get_heights(desc, lons, lats, sizeofArray(lons), vf_heights))) {
    GMT_Close_VirtualFile(desc->gmt_sess, vf_heights);
    printf("Fail: Unable to get heights\n");
    return;
  }

  struct GMT_DATASET *ds_heights = (struct GMT_DATASET *)GMT_Read_VirtualFile(desc->gmt_sess, vf_heights);
  size_t n_points = ds_heights->n_records;
  if (n_points != (sizeofArray(tv))) {
    GMT_Close_VirtualFile(desc->gmt_sess, vf_heights);
    printf("Fail: Expected %ld points, not %ld\n", sizeofArray(tv), n_points);
    return;
  }

  double *heights = ds_heights->table[0][0].segment[0][0].data[2];
  for (size_t i = 0; i < n_points; i++) {
    if (heights[i] != tv[i]) {
      printf("Fail: Expected height at i=%ld, to be %.16f, not %.16f\n", i, tv[i], heights[i]);
      GMT_Close_VirtualFile(desc->gmt_sess, vf_heights);
      return;
    }
  }

  GMT_Close_VirtualFile(desc->gmt_sess, vf_heights);
  printf("Pass\n");
}

